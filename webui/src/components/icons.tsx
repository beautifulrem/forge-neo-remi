/**
 * The app's icon set: Phosphor (MIT), under the names the code already used
 * (they started as Lucide's). One place to choose a glyph for a meaning.
 * Plain re-exports, one module per glyph, so each icon lands in the chunk
 * that draws it. The weight and size defaults come from `IconDefaults`
 * (`bold`: Phosphor's regular is too faint at the 14–16 px the UI draws most
 * icons); pass `weight="fill"` for a current selection.
 */
